import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export function splitSql(sql) {
  const result = [];
  let start = 0, mode = '', tag = '', depth = 0, escape = false, hasCode = false;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i], next = sql[i + 1];
    if (mode === 'line') { if (c === '\n') mode = ''; continue; }
    if (mode === 'block') {
      if (c === '/' && next === '*') { depth++; i++; }
      else if (c === '*' && next === '/') { if (--depth === 0) mode = ''; i++; }
      continue;
    }
    if (mode === 'dollar') { if (sql.startsWith(tag, i)) { i += tag.length - 1; mode = ''; } continue; }
    if (mode === 'single' || mode === 'double') {
      const quote = mode === 'single' ? "'" : '"';
      if (mode === 'single' && escape && c === '\\') { i++; continue; }
      if (c === quote) { if (next === quote) i++; else mode = ''; }
      continue;
    }
    if (c === '-' && next === '-') { mode = 'line'; i++; continue; }
    if (c === '/' && next === '*') { mode = 'block'; depth = 1; i++; continue; }
    if (c === ';') { if (hasCode) result.push(sql.slice(start, i + 1).trim()); start = i + 1; hasCode = false; continue; }
    if (!/\s/.test(c)) hasCode = true;
    if (c === "'") { escape = /[eE]/.test(sql[i - 1] || '') && !/[\w$]/.test(sql[i - 2] || ''); mode = 'single'; }
    else if (c === '"') mode = 'double';
    else if (c === '$') { const found = sql.slice(i).match(/^(?:\$[A-Za-z_][A-Za-z0-9_]*\$|\$\$)/); if (found) { tag = found[0]; mode = 'dollar'; i += tag.length - 1; } }
  }
  if (mode && mode !== 'line') throw new Error(`Unterminated SQL ${mode}`);
  if (hasCode) result.push(sql.slice(start).trim());
  return result;
}
const quote = text => "'" + text.replaceAll("'", "''") + "'";
function dollar(text, label) { let delimiter = `$eva_${label}$`; while (text.includes(delimiter)) delimiter = delimiter.slice(0,-1) + '_$'; return delimiter + text + delimiter; }
export function readMigrations(root) {
  return fs.readdirSync(path.join(root, 'supabase/migrations')).filter(name => /^\d{14}_.+\.sql$/.test(name)).sort().map(file => {
    const [,version,name] = file.match(/^(\d{14})_(.+)\.sql$/);
    const sql = fs.readFileSync(path.join(root,'supabase/migrations',file),'utf8').replace(/\r\n/g,'\n');
    return { file, version, name, statements: splitSql(sql) };
  });
}
export function renderBundle(migrations) {
  if (!migrations.length) throw new Error('No migrations');
  const versions = `ARRAY[${migrations.map(m=>quote(m.version)).join(',')}]::text[]`;
  const appTables = `ARRAY['profiles','learning_sets','vocabulary_cards','study_sessions','study_attempts','study_progress','ai_batches','ai_usage_daily','ai_rate_buckets','ai_request_keys']::text[]`;
  let output = `-- GENERATED by node scripts/build-supabase-dashboard.mjs. Do not edit by hand.
-- Target: English Vocab Arcade. Verify Dashboard project before running.
-- Website currently uses https://qtqvytchmlqojolkobmw.supabase.co .
-- SQL Editor role: postgres. Run the WHOLE file once, not selected lines.
-- Supports a fresh database or an existing exact migration-history prefix.
-- Unknown/partial manually created schemas are refused; no application tables are dropped.
-- All schema changes and migration-history entries commit together or roll back together.
BEGIN;
DO $eva_preflight$
DECLARE
  applied text[] := ARRAY[]::text[];
  expected text[] := ${versions};
  app_count integer; other_count integer; required_count integer;
BEGIN
  IF to_regclass('auth.users') IS NULL THEN RAISE EXCEPTION 'Supabase auth.users is missing. Use the correct hosted Supabase project.'; END IF;
  IF to_regclass('supabase_migrations.schema_migrations') IS NOT NULL THEN
    EXECUTE 'SELECT coalesce(array_agg(version ORDER BY version), ARRAY[]::text[]) FROM supabase_migrations.schema_migrations' INTO applied;
  END IF;
  IF cardinality(applied)>cardinality(expected) OR (cardinality(applied)>0 AND applied IS DISTINCT FROM expected[1:cardinality(applied)]) THEN
    RAISE EXCEPTION 'Different/newer migration history. Stop and inspect this project; do not overwrite it.';
  END IF;
  SELECT count(*) FILTER(WHERE c.relname=ANY(${appTables})), count(*) FILTER(WHERE NOT c.relname=ANY(${appTables}))
  INTO app_count, other_count
  FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
  WHERE n.nspname='public' AND c.relkind IN ('r','p','v','m','f')
    AND NOT EXISTS(SELECT 1 FROM pg_depend d WHERE d.classid='pg_class'::regclass AND d.objid=c.oid AND d.deptype='e');
  required_count := CASE WHEN cardinality(applied)=0 THEN 0 WHEN cardinality(applied)<3 THEN 3 WHEN cardinality(applied)<4 THEN 6 ELSE 10 END;
  IF other_count>0 OR app_count<>required_count THEN
    RAISE EXCEPTION 'Schema exists without matching migration history (app tables %, expected %, other tables %). Stop and inspect; nothing has been changed.',app_count,required_count,other_count;
  END IF;
  IF cardinality(applied)=0 AND EXISTS(SELECT 1 FROM pg_trigger WHERE tgrelid='auth.users'::regclass AND tgname='on_auth_user_created' AND NOT tgisinternal) THEN
    RAISE EXCEPTION 'An Auth profile trigger already exists. Stop and inspect before replacing another application trigger.';
  END IF;
END;
$eva_preflight$;
CREATE SCHEMA IF NOT EXISTS supabase_migrations AUTHORIZATION postgres;
CREATE TABLE IF NOT EXISTS supabase_migrations.schema_migrations(version text PRIMARY KEY, statements text[], name text);
REVOKE ALL ON SCHEMA supabase_migrations FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE supabase_migrations.schema_migrations FROM PUBLIC, anon, authenticated;
`;
  migrations.forEach((migration,index)=>{
    const commands = migration.statements.map((statement,i)=>`    EXECUTE ${dollar(statement,`statement_${index}_${i}`)};`).join('\n');
    const history = `ARRAY[${migration.statements.map((statement,i)=>dollar(statement,`history_${index}_${i}`)).join(',\n')}]::text[]`;
    const body = `BEGIN
  IF NOT EXISTS(SELECT 1 FROM supabase_migrations.schema_migrations WHERE version=${quote(migration.version)}) THEN
${commands}
    INSERT INTO supabase_migrations.schema_migrations(version,name,statements) VALUES(${quote(migration.version)},${quote(migration.name)},${history});
  END IF;
END;`;
    output += `\n-- ${migration.file}\nDO ${dollar(body,`apply_${index}`)};\n`;
  });
  output += `
NOTIFY pgrst, 'reload schema';
COMMIT;
SELECT 'English Vocab Arcade schema ready' AS result,
  to_regclass('public.learning_sets') IS NOT NULL AS learning_sets_exists,
  (SELECT count(*) FROM supabase_migrations.schema_migrations) AS applied_migrations,
  has_table_privilege('anon','public.learning_sets','SELECT') AS public_explore_enabled,
  NOT has_function_privilege('anon','public.save_session_state_v1(uuid,integer,jsonb,bigint,text)','EXECUTE') AS anonymous_session_writes_blocked;
`;
  return output;
}
